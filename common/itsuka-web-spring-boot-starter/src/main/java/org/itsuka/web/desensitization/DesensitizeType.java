package org.itsuka.web.desensitization;

/**
 * 脱敏类型枚举
 * 定义各种常见脱敏规则
 *
 * @author Itsuka
 * @since 2023/12/10
 */
public enum DesensitizeType {
    /**
     * 用户名脱敏
     * 规则：保留第一个字符，其余用*代替，如：张***
     */
    USERNAME,

    /**
     * 手机号脱敏
     * 规则：保留前3位和后4位，中间用*代替，如：138****1234
     */
    PHONE,

    /**
     * 邮箱脱敏
     * 规则：邮箱前缀仅显示第一个字母，@前及后续域名显示，如：d**@email.com
     */
    EMAIL,

    /**
     * 身份证号脱敏
     * 规则：保留前6位和后4位，中间用*代替，如：110105********1234
     */
    ID_CARD,

    /**
     * 银行卡号脱敏
     * 规则：保留前6位和后4位，中间用*代替，如：622202************1234
     */
    BANK_CARD,

    /**
     * 密码脱敏
     * 规则：全部用*代替，如：******
     */
    PASSWORD,

    /**
     * 地址脱敏
     * 规则：从第6位开始隐藏，如：北京市******
     */
    ADDRESS,

    /**
     * 自定义脱敏
     * 规则：需要指定保留前几位和后几位
     */
    CUSTOM
}